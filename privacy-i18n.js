  const STORAGE_KEY = "aitalk-privacy-lang";

  function getLangMeta(code) {
    return LANGS.find((l) => l.code === code) || LANGS[0];
  }

  function apply(code) {
    const meta = getLangMeta(code);
    const dict = T[code] || T.en;
    document.documentElement.lang = code;
    document.documentElement.dir = meta.dir;
    document.title = dict.docTitle;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-lang-current]").forEach((el) => {
      el.textContent = meta.label;
    });

    document.querySelectorAll(".lang-menu button").forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === code);
    });

    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch (_) {}

    const url = new URL(window.location.href);
    if (url.searchParams.get("lang") !== code) {
      url.searchParams.set("lang", code);
      history.replaceState(null, "", url.toString());
    }
  }

  function buildMenus() {
    document.querySelectorAll("[data-lang-menu]").forEach((menu) => {
      menu.innerHTML = "";
      LANGS.forEach((lang) => {
        const btn = document.createElement("button");
        btn.type = "button";
        btn.setAttribute("data-lang", lang.code);
        btn.textContent = lang.label;
        btn.addEventListener("click", () => {
          apply(lang.code);
          document.querySelectorAll(".lang-switch").forEach((s) => s.classList.remove("open"));
        });
        menu.appendChild(btn);
      });
    });
  }

  function wireToggles() {
    document.querySelectorAll(".lang-switch").forEach((wrap) => {
      const btn = wrap.querySelector(".lang-switch-btn");
      if (!btn) return;
      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        const open = wrap.classList.contains("open");
        document.querySelectorAll(".lang-switch").forEach((s) => s.classList.remove("open"));
        if (!open) wrap.classList.add("open");
      });
    });
    document.addEventListener("click", () => {
      document.querySelectorAll(".lang-switch").forEach((s) => s.classList.remove("open"));
    });
  }

  function initialCode() {
    const params = new URLSearchParams(window.location.search);
    const fromUrl = params.get("lang");
    if (fromUrl && T[fromUrl]) return fromUrl;
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && T[saved]) return saved;
    } catch (_) {}
    return "en";
  }

  document.addEventListener("DOMContentLoaded", () => {
    buildMenus();
    wireToggles();
    apply(initialCode());
  });
